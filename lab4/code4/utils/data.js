function getStars(moves, parMoves) {
  if (!moves) return 0
  if (moves <= parMoves) return 3
  if (moves <= Math.ceil(parMoves * 1.2)) return 2
  return 1
}

function isLevelUnlocked(levelId, best, practiceMode) {
  return practiceMode || levelId === 0 || Number(best[levelId - 1]) > 0
}

